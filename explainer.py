# مرشد الإعلال والإبدال التعليمي - المحرك الموسّع الشامل
from camel_tools.morphology.database import MorphologyDB
from camel_tools.morphology.analyzer import Analyzer

def init_analyzer():
    """تحميل قاعدة بيانات CAMeL Tools"""
    db = MorphologyDB.builtin_db()
    return Analyzer(db)

def explain_morphology(word, root, pattern):
    """المحرك الصرفي الشامل لتشخيص وتطليل قواعد الإعلال والإبدال والإدغام"""
    if not root or '.' not in root:
        return {
            "نوع التغيير": "غير محدد",
            "الأصل المفترض": word,
            "التعليل التعليمي": "كلمة جامدة أو لا تنطبق عليها قواعد الأفعال المشتقة القياسية."
        }

    roots = root.split('.')
    r1 = roots[0] if len(roots) > 0 else ''
    r2 = roots[1] if len(roots) > 1 else ''
    r3 = roots[2] if len(roots) > 2 else ''

    # 1. إبدال تاء (افتعل) طاءً بعد حروف الإطباق (ص، ض، ط، ظ)
    if r1 in ['ص', 'ض', 'ط', 'ظ'] and 'ط' in word and not word.startswith('ط'):
        return {
            "نوع التغيير": "إبدال صرفي (إبدال تاء افتعل طاءً)",
            "الأصل المفترض": f"اِ{r1}ْتَ{r2}َ{r3}",
            "التعليل التعليمي": f"وقعت تاء (اِفْتَعَلَ) بعد حرف الإطباق ({r1})، فُقلبت التاء طاءً لتناسب الإطباق صوتاً، فصارت ({word})."
        }

    # 2. إبدال تاء (افتعل) دالاً بعد حروف الجهر (ز، ذ، د)
    if r1 in ['ز', 'ذ', 'د'] and 'د' in word and not word.startswith('د'):
        return {
            "نوع التغيير": "إبدال صرفي (إبدال تاء افتعل دالاً)",
            "الأصل المفترض": f"اِ{r1}ْتَ{r2}َ{r3}",
            "التعليل التعليمي": f"وقعت تاء (اِفْتَعَلَ) بعد حرف الجهر ({r1})، فُقلبت التاء دالاً للمجانسة الصوتية، فصارت ({word})."
        }

    # 3. إبدال الفاء الواوية تاءً وإدغامها في تاء (افتعل)
    if word.startswith(('ات', 'إت', 'اِت')) or (r1 in ['و', 'ي', '#'] and ('تَّ' in word or 'تّ' in word or word.startswith('ات'))):
        return {
            "نوع التغيير": "إبدال وإدغام (إبدال الواو تاءً)",
            "الأصل المفترض": f"اِوْتَ{r2}َ{r3}",
            "التعليل التعليمي": f"وقعت الواو فاءً في صيغة (اِفْتَعَلَ)، فُقلبت الواو تاءً وأُدغمت في تاء افتعل للتخفيف، فصارت ({word})."
        }

    # 4. الإدغام الصرفي في الفعل المضعّف (عَدَّ، يَمُدُّ، اسْتَعَدَّ)
    if r2 == r3 or (r2 != '' and r3 in ['#', r2]) or 'ّ' in word:
        if len(word) <= 4 or word.startswith(('است', 'اِست')):
            return {
                "نوع التغيير": "إدغام صرفي (تضعيف)",
                "الأصل المفترض": f"{r1}َ{r2}َ{r2}",
                "التعليل التعليمي": f"اجتمع حرفان متماثلان متحركان ({r2} + {r2})، فُسكن الأول وأُدغم في الثاني طلباً للخفة، فصارا حرفاً مشدداً ({word})."
            }

    # 5. الإعلال بالنقل والتسكين (يَقُولُ، يَبِيعُ، يَخَافُ)
    if (r2 in ['و', 'ي', '#']) and word.startswith(('ي', 'ت', 'أ', 'ن')) and any(v in word for v in ['و', 'ي']) and len(word) >= 4:
        vowel_letter = 'و' if 'و' in word else 'ي'
        return {
            "نوع التغيير": "إعلال بالنقل والتسكين",
            "الأصل المفترض": f"يَ{r1}ْ{vowel_letter}ُ{r3}",
            "التعليل التعليمي": f"تحركت عين الفعل المعتلة ({r2}) وكان ما قبلها ساكناً صحيحاً ({r1})، فُنقلت حركة العين إلى الساكن قبلها لثقل الضمة/الكسرة على حرف العلة، فصارت ({word})."
        }

    # 6. الإعلال بالقلب (الأجوف/الناقص الماضي: قَالَ، بَاعَ، دَعَا، رَمَى)
    if (r2 in ['و', 'ي', '#']) and ('ا' in word or word.endswith('ى')) and len(word) <= 4:
        return {
            "نوع التغيير": "إعلال بالقلب (قلب الواو/الياء ألفاً)",
            "الأصل المفترض": f"{r1}َوَلَ",
            "التعليل التعليمي": f"تحركت عين/لام الفعل المعتلة وانفتح ما قبلها ({r1}َ)، فُقلبت ألفاً طلباً للتخفيف، فصارت ({word})."
        }

    # 7. الإعلال بالحذف (فعل الأمر من الأجوف أو مضارع المثال: قُلْ، بِعْ، يَعِدُ)
    if (r2 in ['و', 'ي', '#'] or r1 in ['و', '#']) and len(word) <= 3:
        return {
            "نوع التغيير": "إعلال بالحذف (التقاء الساكنين / حذف فاء المثال)",
            "الأصل المفترض": f"اُ{r1}ْ{('و' if r2 in ['و','#'] else 'ي')}ُ{r3}" if len(word) <= 2 else f"يَوْ{r2}ِ{r3}",
            "التعليل التعليمي": f"حُذفت عين/فاء الفعل المعتلة منعاً لالتقاء الساكنين عند بناء الأمر على السكون أو لوقوعها بين فتحة وكسرة، فصارت ({word})."
        }

    return {
        "نوع التغيير": "سالم / قياسي",
        "الأصل المفترض": word,
        "التعليل التعليمي": "الكلمة تجري على الأصل القياسي دون إعلال أو إبدال ظاهر."
    }

def analyze_word(analyzer, word):
    analyses = analyzer.analyze(word)
    if not analyses:
        return {"الكلمة المستعملة": word, "خطأ": "لم يتم العثور على تحليل صرفي."}
    
    top = analyses[0]
    root = top.get('root', '')
    pattern = top.get('pattern', '')
    explanation = explain_morphology(word, root, pattern)

    return {
        "الكلمة المستعملة": word,
        "الجذر الصرفي": root,
        "الوزن": pattern,
        **explanation
    }

if __name__ == "__main__":
    analyzer = init_analyzer()
    print("=== مرشد الإعلال والإبدال التعليمي - الاختبار الموسع ===\n")
    
    # قائمة الشواهد الصرفية المتنوعة
    test_words = [
        "اصطبر",   # إبدال تاء افتعل طاءً
        "ازدحم",   # إبدال تاء افتعل دالاً
        "اتصل",    # إبدال الواو تاءً وإدغامها
        "قال",     # إعلال بالقلب
        "يقول",    # إعلال بالنقل والتسكين
        "قل",      # إعلال بالحذف (التقاء الساكنين)
        "عد",      # إدغام صرفي (تضعيف)
        "كتب"      # فعل سالم قياسي
    ]
    
    for word in test_words:
        res = analyze_word(analyzer, word)
        print(f"الكلمة: {res['الكلمة المستعملة']}")
        print(f"الجذر: {res['الجذر الصرفي']} | الوزن: {res['الوزن']}")
        print(f"نوع التغيير: {res['نوع التغيير']}")
        print(f"الشرح: {res['التعليل التعليمي']}")
        print("-" * 60)
